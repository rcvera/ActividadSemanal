CREATE TABLE clientes (
                          id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre    VARCHAR(255) NOT NULL,
                          telefono  VARCHAR(255) NOT NULL
);

CREATE TABLE reparaciones (
                              id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              bicicleta   VARCHAR(255)     NOT NULL,
                              cliente_id  INTEGER          NOT NULL,
                              costo       DOUBLE PRECISION NOT NULL DEFAULT 0,
                              lista       BOOLEAN          NOT NULL DEFAULT FALSE,
                              CONSTRAINT fk_reparacion_cliente
                                  FOREIGN KEY (cliente_id) REFERENCES clientes (id)
);

CREATE TABLE reparacion_repuestos (
                                      reparacion_id  INTEGER      NOT NULL,
                                      repuesto       VARCHAR(255),
                                      CONSTRAINT fk_repuesto_reparacion
                                          FOREIGN KEY (reparacion_id) REFERENCES reparaciones (id) ON DELETE CASCADE
);

CREATE INDEX idx_reparaciones_cliente ON reparaciones (cliente_id);
CREATE INDEX idx_repuestos_reparacion ON reparacion_repuestos (reparacion_id);

